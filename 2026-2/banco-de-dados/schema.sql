-- PostgreSQL 18. Executar em banco vazio com ON_ERROR_STOP.
BEGIN;
CREATE TABLE usuario (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome text NOT NULL CHECK (btrim(nome) <> ''),
 email text NOT NULL UNIQUE CHECK (btrim(email) <> ''),
 senha_hash text NOT NULL CHECK (btrim(senha_hash) <> '')
);
CREATE TABLE pesquisa (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 titulo text NOT NULL CHECK (btrim(titulo) <> ''),
 administrador_id bigint NOT NULL REFERENCES usuario(id),
 proprietario_id bigint NOT NULL REFERENCES usuario(id)
);
CREATE TABLE categoria (
 pesquisa_id bigint NOT NULL REFERENCES pesquisa(id),
 id bigint NOT NULL,
 nome text NOT NULL CHECK (btrim(nome) <> ''),
 PRIMARY KEY (pesquisa_id, id), UNIQUE (pesquisa_id, nome)
);
CREATE TABLE questao (
 pesquisa_id bigint NOT NULL,
 categoria_id bigint NOT NULL,
 id bigint NOT NULL,
 enunciado text NOT NULL CHECK (btrim(enunciado) <> ''),
 PRIMARY KEY (pesquisa_id, categoria_id, id),
 FOREIGN KEY (pesquisa_id, categoria_id) REFERENCES categoria(pesquisa_id, id)
);
CREATE TABLE opcao (
 pesquisa_id bigint NOT NULL,
 categoria_id bigint NOT NULL,
 questao_id bigint NOT NULL,
 id bigint NOT NULL,
 descricao text NOT NULL CHECK (btrim(descricao) <> ''),
 PRIMARY KEY (pesquisa_id, categoria_id, questao_id, id),
 FOREIGN KEY (pesquisa_id, categoria_id, questao_id) REFERENCES questao(pesquisa_id, categoria_id, id)
);
CREATE TABLE participacao (
 pesquisa_id bigint NOT NULL,
 usuario_id bigint NOT NULL REFERENCES usuario(id),
 categoria_id bigint NOT NULL,
 concluida boolean NOT NULL DEFAULT false,
 PRIMARY KEY (pesquisa_id, usuario_id),
 FOREIGN KEY (pesquisa_id, categoria_id) REFERENCES categoria(pesquisa_id, id)
);
-- Somente tokens ativos existem. Exclusão remove hash e vínculo ao usuário.
CREATE TABLE token_acesso (
 token_hash text PRIMARY KEY CHECK (token_hash ~ '^[0-9a-f]{64}$'),
 pesquisa_id bigint NOT NULL,
 usuario_id bigint NOT NULL,
 UNIQUE (pesquisa_id, usuario_id),
 FOREIGN KEY (pesquisa_id, usuario_id) REFERENCES participacao(pesquisa_id, usuario_id)
);
CREATE TABLE resposta_anonima (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
 pesquisa_id bigint NOT NULL,
 categoria_id bigint NOT NULL,
 FOREIGN KEY (pesquisa_id, categoria_id) REFERENCES categoria(pesquisa_id, id)
);
CREATE TABLE item_resposta (
 resposta_id uuid NOT NULL REFERENCES resposta_anonima(id),
 questao_id bigint NOT NULL,
 opcao_id bigint NOT NULL,
 PRIMARY KEY (resposta_id, questao_id)
);
-- Contexto é derivado da resposta para evitar dependência transitiva no item (3FN).
CREATE FUNCTION validar_item() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $$
BEGIN
 PERFORM 1 FROM resposta_anonima r JOIN opcao o
 ON (o.pesquisa_id,o.categoria_id)=(r.pesquisa_id,r.categoria_id)
 WHERE r.id=NEW.resposta_id AND o.questao_id=NEW.questao_id AND o.id=NEW.opcao_id
 FOR KEY SHARE OF r,o;
 IF NOT FOUND THEN RAISE EXCEPTION 'Opção incompatível com a resposta' USING ERRCODE='23503'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER item_contexto BEFORE INSERT OR UPDATE ON item_resposta
FOR EACH ROW EXECUTE FUNCTION validar_item();
-- Estrutura publicada e respostas são imutáveis nesta entrega acadêmica.
CREATE FUNCTION impedir_alteracao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Registro imutável; crie uma nova pesquisa'; END $$;
CREATE TRIGGER opcao_imutavel BEFORE UPDATE OR DELETE ON opcao
FOR EACH ROW EXECUTE FUNCTION impedir_alteracao();
CREATE TRIGGER resposta_imutavel BEFORE UPDATE OR DELETE ON resposta_anonima
FOR EACH ROW EXECUTE FUNCTION impedir_alteracao();
CREATE TRIGGER item_imutavel BEFORE UPDATE OR DELETE ON item_resposta
FOR EACH ROW EXECUTE FUNCTION impedir_alteracao();
CREATE FUNCTION proteger_participacao() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF OLD.concluida THEN RAISE EXCEPTION 'Participação concluída é imutável'; END IF;
 IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER participacao_concluida BEFORE UPDATE OR DELETE ON participacao
FOR EACH ROW EXECUTE FUNCTION proteger_participacao();
CREATE FUNCTION validar_token() RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE feita boolean;
BEGIN
 SELECT concluida INTO feita FROM participacao
 WHERE pesquisa_id=NEW.pesquisa_id AND usuario_id=NEW.usuario_id FOR UPDATE;
 IF feita THEN RAISE EXCEPTION 'Não é possível emitir token para participação concluída'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER token_participacao BEFORE INSERT OR UPDATE ON token_acesso
FOR EACH ROW EXECUTE FUNCTION validar_token();
-- Contrato acadêmico: questões fechadas, uma opção por questão, todas obrigatórias.
-- Não retorna identificador de resposta ao chamador.
CREATE FUNCTION finalizar_questionario(p_hash text, p_itens jsonb)
RETURNS void LANGUAGE plpgsql
SET search_path = pg_catalog, public, pg_temp AS $$
DECLARE t token_acesso%ROWTYPE; p participacao%ROWTYPE; r uuid;
BEGIN
 SELECT * INTO t FROM token_acesso WHERE token_hash = p_hash FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Token inválido ou consumido'; END IF;
 SELECT * INTO p FROM participacao
 WHERE pesquisa_id=t.pesquisa_id AND usuario_id=t.usuario_id FOR UPDATE;
 IF p.concluida THEN RAISE EXCEPTION 'Participação já concluída'; END IF;
 IF jsonb_typeof(p_itens) IS DISTINCT FROM 'array' THEN
   RAISE EXCEPTION 'Itens devem ser um array';
 END IF;
 IF jsonb_array_length(p_itens) = 0 OR jsonb_array_length(p_itens) <>
 (SELECT count(*) FROM questao WHERE pesquisa_id=p.pesquisa_id AND categoria_id=p.categoria_id)
 THEN RAISE EXCEPTION 'Questionário incompleto'; END IF;
 INSERT INTO resposta_anonima(pesquisa_id,categoria_id)
 VALUES(p.pesquisa_id,p.categoria_id) RETURNING id INTO r;
 INSERT INTO item_resposta
 SELECT r,x.questao_id,x.opcao_id
 FROM jsonb_to_recordset(p_itens) AS x(questao_id bigint,opcao_id bigint);
 UPDATE participacao SET concluida=true
 WHERE pesquisa_id=p.pesquisa_id AND usuario_id=p.usuario_id;
 DELETE FROM token_acesso WHERE token_hash=p_hash;
END $$;
COMMIT;
